"""Normalise the approved whole-strip pet edit without changing scale per frame."""
from pathlib import Path
from PIL import Image, ImageChops, ImageFilter
from collections import deque
import argparse, json

root=Path(__file__).resolve().parents[1]
args=argparse.ArgumentParser()
args.add_argument('source',type=Path)
options=args.parse_args()
source=Image.open(options.source).convert('RGBA')
# The generated strip's six naturally spaced rows, reviewed against contact gaps.
ys=[0,222,442,661,869,1060,1254]
atlas=Image.new('RGBA',(1024,1152))
frames={}
def main_sprite(slot):
    # Ignore tiny neighbouring-row tips and detached shadow flecks from the raw edit.
    w,h=slot.size; alpha=slot.getchannel('A'); pixels=list(alpha.getdata());seen=bytearray(w*h);largest=[]
    for at,v in enumerate(pixels):
        if v<110 or seen[at]:continue
        queue=deque([at]);seen[at]=1;part=[]
        while queue:
            i=queue.popleft();part.append(i);x=i%w;y=i//w
            for nx,ny in [(x-1,y),(x+1,y),(x,y-1),(x,y+1)]:
                if 0<=nx<w and 0<=ny<h:
                    j=ny*w+nx
                    if pixels[j]>=110 and not seen[j]:seen[j]=1;queue.append(j)
        if len(part)>len(largest):largest=part
    mask=Image.new('L',slot.size); values=bytearray(w*h)
    for i in largest:values[i]=255
    mask.frombytes(bytes(values));mask=mask.filter(ImageFilter.MaxFilter(7))
    slot.putalpha(ImageChops.multiply(alpha,mask));return slot
for pet,offset in [('skyla',0),('maisie',2),('sandy',4)]:
    output=[]
    for n in range(8):
        row=offset+n//4; col=n%4
        slot=main_sprite(source.crop((round(col*source.width/4),ys[row],round((col+1)*source.width/4),ys[row+1])))
        alpha=slot.getchannel('A');mask=alpha.point(lambda v:255 if v>=110 else 0);bbox=mask.getbbox()
        if not bbox:raise ValueError((pet,n,'empty cell'))
        # One 0.80 scale for the entire atlas; no per-frame stretching or fitting.
        scale=.80; sw,sh=round(slot.width*scale),round(slot.height*scale)
        slot=slot.resize((sw,sh),Image.Resampling.LANCZOS)
        a=slot.getchannel('A');slot.putalpha(a.point(lambda v:0 if v<50 else v))
        x=round(128-slot.width/2);y=round(184-bbox[3]*scale)
        frame=Image.new('RGBA',(256,192));frame.alpha_composite(slot,(x,y))
        ax=(n%4)*256;ay=(offset+n//4)*192
        atlas.alpha_composite(frame,(ax,ay))
        output.append({'x':ax,'y':ay,'w':256,'h':192,'ax':128,'ay':184})
    frames[pet]={'frames':output,'width':{'skyla':1.4,'maisie':1.7,'sandy':2.05}[pet]}
asset=root/'assets/home-pets.webp';atlas.save(asset,'WEBP',quality=88,method=6,exact=True)
meta={'w':1024,'h':1152,'states':{'idle':0,'walk':[1,2],'wag':[3,4],'sleep':5,'stretch':6,'feed':7},'pets':frames}
(root/'src/home-pets-meta.js').write_text('// Generated by tools/prepare-home-pets.py from approved whole-sheet edit.\nexport const HOME_PETS_META = '+json.dumps(meta,separators=(',',':'))+';\n')
preview=Image.new('RGBA',atlas.size,(43,39,51,255));preview.alpha_composite(atlas)
preview.convert('RGB').save(root/'docs/plans/home-companions/pet-animation-preview.jpg',quality=92)
print(asset.stat().st_size,asset)
