#!/usr/bin/env python3
"""Pack generated furniture art; Pillow only crops/normalises the supplied art.

Run from any directory: python voxel/tools/bake-furniture-set-icons.py
The source remains untouched. No furniture is painted or procedurally rendered.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/furniture-set-concepts/source.png"
OUTPUT = ROOT / "assets/furniture-set-icons"
IDS = [
    "moonlit-reading-set", "rattlewood-workshop-set",
    "midnight-reading-bench", "shelf-floating",
    "household-plum-mug", "lantern-entry-console",
    "household-coat-hooks", "shelf-bracket",
]
COLUMNS, ROWS, CELL, INSET = 4, 2, 128, 10


def main():
    source = Image.open(SOURCE).convert("RGBA")
    atlas = Image.new("RGBA", (COLUMNS * CELL, ROWS * CELL))
    records = []
    (OUTPUT / "individual").mkdir(parents=True, exist_ok=True)
    for index, item_id in enumerate(IDS):
        col, row = index % COLUMNS, index // COLUMNS
        bounds = (col * source.width // COLUMNS, row * source.height // ROWS,
                  (col + 1) * source.width // COLUMNS, (row + 1) * source.height // ROWS)
        tile = source.crop(bounds)
        # The generator's transparent canvas carries low-alpha RGB speckle.
        # Remove only <24/255 alpha, retaining object antialiasing and amber light.
        alpha = tile.getchannel("A")
        tile.putalpha(alpha.point(lambda value: 0 if value < 24 else value))
        content = tile.getbbox()
        if not content:
            raise ValueError(f"Empty source cell for {item_id}")
        tile = tile.crop(content)
        tile.thumbnail((CELL - 2 * INSET, CELL - 2 * INSET), Image.Resampling.LANCZOS)
        normalised = Image.new("RGBA", (CELL, CELL))
        normalised.alpha_composite(tile, ((CELL - tile.width) // 2, (CELL - tile.height) // 2))
        normalised.save(OUTPUT / "individual" / f"{item_id}.png", optimize=True)
        atlas.alpha_composite(normalised, (col * CELL, row * CELL))
        records.append({"id": item_id, "column": col, "row": row,
                        "sourceBounds": list(bounds), "alphaBounds": list(content),
                        "renderSize": list(tile.size)})
    atlas.save(OUTPUT / "furniture-sets.webp", lossless=True, method=6)
    # Review both normalised 128px art and actual 52px menu-size readability.
    preview = Image.new("RGB", (640, 404), "#271e31")
    draw = ImageDraw.Draw(preview)
    for index, item_id in enumerate(IDS):
        x, y = index % COLUMNS * 160, index // COLUMNS * 202
        tile = atlas.crop((index % COLUMNS * CELL, index // COLUMNS * CELL,
                           (index % COLUMNS + 1) * CELL, (index // COLUMNS + 1) * CELL))
        preview.paste(tile, (x + 16, y), tile)
        tiny = tile.resize((52, 52), Image.Resampling.LANCZOS)
        preview.paste(tiny, (x + 54, y + 132), tiny)
        short_name = item_id.replace("household-", "").replace("workshop-", "")
        draw.text((x + 5, y + 188), short_name[:25], fill="#e9d9b9")
    preview.save(OUTPUT / "contact-preview.jpg", quality=94, subsampling=0)
    manifest = {
        "generatedBy": "voxel/tools/bake-furniture-set-icons.py",
        "source": str(SOURCE.relative_to(ROOT)),
        "sourceSha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        "sourceSize": list(source.size),
        "grid": {"columns": COLUMNS, "rows": ROWS, "cell": CELL, "inset": INSET},
        "items": records,
    }
    (OUTPUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    metadata = "// Generated by tools/bake-furniture-set-icons.py; change source art, then rebake.\n"
    metadata += "export const FURNITURE_SET_GRID = Object.freeze(" + json.dumps(manifest["grid"]) + ");\n"
    metadata += "export const FURNITURE_SET_ICONS = Object.freeze(" + json.dumps({
        item["id"]: {"column": item["column"], "row": item["row"]} for item in records
    }, indent=2) + ");\n"
    (ROOT / "src/content/furniture-set-icon-meta.js").write_text(metadata)
    print(f"Packed {len(IDS)} transparent furniture icons: {(OUTPUT / 'furniture-sets.webp').stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
