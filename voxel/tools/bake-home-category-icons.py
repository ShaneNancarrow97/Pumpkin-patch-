#!/usr/bin/env python3
"""Pack generated category art; do not redraw or mirror the source illustrations."""
from PIL import Image, ImageDraw
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'assets/home-category-concepts/source.png'
OUT=ROOT/'assets/home-category-icons'
IDS=['all','seating','tables','beds','storage','lighting','rugs','wall','small','curios','kitchen','bathroom','electronics','laundry','music','pets','books','wallpaper','room','owned']
COLS,ROWS,CELL,INSET=5,4,128,10
image=Image.open(SRC).convert('RGBA')
atlas=Image.new('RGBA',(COLS*CELL,ROWS*CELL))
records=[]
for i,id in enumerate(IDS):
 col,row=i%COLS,i//COLS
 box=(round(col*image.width/COLS),round(row*image.height/ROWS),round((col+1)*image.width/COLS),round((row+1)*image.height/ROWS))
 art=image.crop(box)
 alpha=art.getchannel('A').point(lambda a:a if a>=24 else 0);art.putalpha(alpha)
 bounds=alpha.getbbox()
 if not bounds:raise ValueError('Empty icon '+id)
 art=art.crop(bounds);art.thumbnail((CELL-2*INSET,CELL-2*INSET),Image.Resampling.LANCZOS)
 tile=Image.new('RGBA',(CELL,CELL));tile.alpha_composite(art,((CELL-art.width)//2,(CELL-art.height)//2));atlas.alpha_composite(tile,(col*CELL,row*CELL))
 tile.save(OUT/'individual'/f'{id}.png')
 records.append({'id':id,'column':col,'row':row,'sourceCrop':box,'alphaBounds':list(bounds),'packedSize':list(art.size)})
atlas.save(OUT/'home-categories.webp',lossless=True,method=6)
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
manifest={'source':'../home-category-concepts/source.png','sourceSha256':sha(SRC),'columns':COLS,'rows':ROWS,'cell':CELL,'inset':INSET,'icons':records,'atlasBytes':(OUT/'home-categories.webp').stat().st_size,'atlasSha256':sha(OUT/'home-categories.webp')}
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
meta='// Generated by tools/bake-home-category-icons.py.\nexport const HOME_CATEGORY_GRID = '+json.dumps({'columns':COLS,'rows':ROWS,'cell':CELL})+';\nexport const HOME_CATEGORY_ICONS = '+json.dumps({r['id']:{'column':r['column'],'row':r['row']} for r in records},indent=2)+';\n'
(ROOT/'src/content/home-category-icon-meta.js').write_text(meta)
preview=Image.new('RGB',(COLS*180,ROWS*205),(40,31,50));draw=ImageDraw.Draw(preview)
for r in records:
 tile=Image.open(OUT/'individual'/f"{r['id']}.png");x,y=r['column']*180,r['row']*205
 preview.paste(tile,(x+26,y+2),tile)
 small=tile.resize((32,32),Image.Resampling.LANCZOS);preview.paste(small,(x+72,y+136),small);draw.text((x+12,y+179),r['id'],fill=(245,229,203))
preview.save(OUT/'contact-preview.jpg',quality=94)
print(json.dumps({'atlas':str(OUT/'home-categories.webp'),'bytes':manifest['atlasBytes'],'sha256':manifest['atlasSha256'],'icons':len(records)}))
