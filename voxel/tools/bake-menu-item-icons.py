#!/usr/bin/env python3
"""Pack approved menu paintings; never redraw their shapes or invent a missing icon."""
from pathlib import Path
import argparse, base64, hashlib, html, json
from PIL import Image, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--metadata-only',action='store_true');args=parser.parse_args()
source=ROOT/'assets/menu-item-concepts';output=ROOT/'assets/menu-items'
spec=json.loads((source/'manifest.json').read_text());grid=spec['output'];ids=[id for sheet in spec['sheets'] for id in sheet['ids']]
assert len(ids)==len(set(ids))==grid['columns']*grid['rows']
meta={id:{'column':i%grid['columns'],'row':i//grid['columns']} for i,id in enumerate(ids)}
def write_meta():
 (ROOT/'src/content/village-item-icon-meta.js').write_text('// Generated by tools/bake-menu-item-icons.py; change the source manifest.\nexport const VILLAGE_ITEM_GRID = Object.freeze('+json.dumps(grid)+');\nexport const VILLAGE_ITEM_ICONS = Object.freeze('+json.dumps(meta,indent=2)+');\n')
if args.metadata_only:
 write_meta();print('Metadata prepared; artwork still requires a complete bake.');raise SystemExit

# Find the empty gutters nearest the declared grid, without slicing visible paint.
def edges(alpha,number,axis):
 size=alpha.width if axis==0 else alpha.height
 def score(n):
  line=alpha.crop((n,0,n+1,alpha.height) if axis==0 else (0,n,alpha.width,n+1))
  return sum(v>24 for v in line.tobytes())
 values=[0]
 for i in range(1,number):
  mid=size*i/number;radius=size/number*.12
  choices=range(max(values[-1]+1,int(mid-radius)),min(size,int(mid+radius)+1))
  at=min(choices,key=lambda n:(score(n),abs(n-mid)))
  if score(at)>3:raise ValueError(f'Paint crosses grid boundary {axis}:{i} ({score(at)} pixels)')
  values.append(at)
 return values+[size]

cell=grid['cell'];atlas=Image.new('RGBA',(grid['columns']*cell,grid['rows']*cell));records=[]
for sheet in spec['sheets']:
 path=source/sheet['file'];im=Image.open(path).convert('RGBA');alpha=im.getchannel('A')
 if sum(v==0 for v in alpha.tobytes())<im.width*im.height*.15:raise ValueError(f'{path.name}: no usable transparency')
 xs=edges(alpha,sheet['columns'],0) if 'crops' not in sheet else None;ys=edges(alpha,sheet['rows'],1) if 'crops' not in sheet else None
 for j,id in enumerate(sheet['ids']):
  x=j%sheet['columns'];y=j//sheet['columns']
  if 'crops' in sheet:
   rect=sheet['crops'][j];assert rect['id']==id
   cut=[rect['x'],rect['y'],rect['x']+rect['w'],rect['y']+rect['h']]
  else:cut=[xs[x],ys[y],xs[x+1],ys[y+1]]
  tile=im.crop(cut)
  a=tile.getchannel('A');borders=[a.crop((0,0,a.width,1)),a.crop((0,a.height-1,a.width,a.height)),a.crop((0,0,1,a.height)),a.crop((a.width-1,0,a.width,a.height))]
  if any(any(v>=32 for v in edge.tobytes()) for edge in borders):raise ValueError(f'{id}: artwork touches crop boundary')
  mask=tile.getchannel('A').point(lambda n:255 if n>=12 else 0);box=mask.getbbox()
  if not box:raise ValueError(f'{id}: empty cell')
  # Include the painted glow immediately around the measured object; transparent RGB is irrelevant.
  crop=[max(0,box[0]-3),max(0,box[1]-3),min(tile.width,box[2]+3),min(tile.height,box[3]+3)]
  tile=tile.crop(crop);scale=(cell-2*grid['inset'])/max(tile.size)
  size=(max(1,round(tile.width*scale)),max(1,round(tile.height*scale)));tile=tile.resize(size,Image.Resampling.LANCZOS)
  ix=meta[id]['column']*cell;iy=meta[id]['row']*cell;anchor=[(cell-size[0])//2,(cell-size[1])//2]
  atlas.alpha_composite(tile,(ix+anchor[0],iy+anchor[1]))
  records.append({'id':id,'source':sheet['file'],'sourceSha256':hashlib.sha256(path.read_bytes()).hexdigest(),'sourceCell':cut,'sourceCrop':crop,'scale':scale,'packedSize':size,'offset':anchor,**meta[id]})
output.mkdir(parents=True,exist_ok=True);atlas.save(output/'village-items.webp','WEBP',lossless=True,method=6)
write_meta()
(output/'tiles').mkdir(exist_ok=True)
for id,at in meta.items():
 x=at['column']*cell;y=at['row']*cell
 atlas.crop((x,y,x+cell,y+cell)).save(output/'tiles'/f'{id}.png')
preview=Image.new('RGB',(6*170,6*190),'#21172b');draw=ImageDraw.Draw(preview)
try:font=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',12)
except OSError:font=ImageFont.load_default()
for i,id in enumerate(ids):
 x=i%6;y=i//6;tile=atlas.crop((x*cell,y*cell,(x+1)*cell,(y+1)*cell));preview.paste(tile,(x*170+21,y*190+10),tile)
 draw.text((x*170+85,y*190+150),id,anchor='mm',font=font,fill='#eedcc7')
preview.save(output/'contact.jpg',quality=93)
asset=output/'village-items.webp';manifest={'version':1,'grid':grid,'bytes':asset.stat().st_size,'sha256':hashlib.sha256(asset.read_bytes()).hexdigest(),'decodedRgbaBytes':atlas.width*atlas.height*4,'icons':records}
(output/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
data='data:image/webp;base64,'+base64.b64encode(asset.read_bytes()).decode()
cards=[]
for id in ids:
 icon=meta[id];cards.append(f'<article><i style="--x:{icon["column"]/5*100}%;--y:{icon["row"]/5*100}%" aria-hidden="true"></i><b>{html.escape(id)}</b></article>')
page='''<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Mothlight menu sprites</title><style>*{box-sizing:border-box}body{margin:0;padding:24px;background:#21172b;color:#eedcc7;font:15px system-ui}h1{font-size:24px}p{max-width:700px;line-height:1.6;color:#cbb7d4}main{display:grid;grid-template-columns:repeat(auto-fit,minmax(150px,1fr));gap:12px}article{display:grid;justify-items:center;padding:18px 8px;border:1px solid #dcb67d28;border-radius:16px;background:#35263f}i{display:block;width:96px;height:96px;background-image:url("'''+data+'''");background-size:600% 600%;background-position:var(--x) var(--y)}b{font-size:12px;margin-top:12px;text-align:center}label{display:block;margin:18px 0}input{vertical-align:middle;min-height:44px}</style><h1>Mothlight menu sprites</h1><p>36 transparent illustrated icons. Current menus use the relevant pieces; future-district materials remain locked by existing game progression.</p><label>Preview size <input id="size" type="range" min="24" max="128" value="96"> <output id="label">96 px</output></label><main>'''+''.join(cards)+'''</main><script>document.getElementById('size').oninput=e=>{document.querySelectorAll('i').forEach(i=>{i.style.width=i.style.height=e.target.value+'px'});document.getElementById('label').textContent=e.target.value+' px'};</script></html>'''
(output/'preview.html').write_text(page)
print(json.dumps({'icons':len(ids),'bytes':manifest['bytes'],'sha256':manifest['sha256']}))
