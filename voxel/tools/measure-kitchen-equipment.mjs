// These models need no sprite atlas or DOM, so their collision sizes can be
// measured directly in Node without launching another browser.
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import * as THREE from "three";
import { KITCHEN_EQUIPMENT } from "../src/content/kitchen-equipment.js";
import { kitchenProp } from "../src/kitchen-props.js";

const round = n => Math.round(n * 1000) / 1000;
const sizes = Object.fromEntries(KITCHEN_EQUIPMENT.map(item => {
  const box = new THREE.Box3().setFromObject(kitchenProp(item.id));
  return [item.id, { box: [box.min.x, box.max.x, box.min.z, box.max.z, box.max.y].map(round) }];
}));
const out = fileURLToPath(new URL("../src/content/kitchen-equipment-sizes.js", import.meta.url));
fs.writeFileSync(out, "// Generated by tools/measure-kitchen-equipment.mjs from the native kitchen models.\nexport const KITCHEN_EQUIPMENT_SIZES = " + JSON.stringify(sizes, null, 2) + ";\n");
console.log("Measured " + Object.keys(sizes).length + " kitchen pieces.");
