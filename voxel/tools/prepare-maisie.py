from pathlib import Path
from PIL import Image
import json
root=Path(__file__).resolve().parents[1]
source=root/'docs/plans/kitchen-workshop/art/maisie/source.png'
im=Image.open(source).convert('RGBA');cells=[]
for row in range(2):
 for col in range(4):
  cell=im.crop((col*im.width//4,row*im.height//2,(col+1)*im.width//4,(row+1)*im.height//2))
  box=cell.getchannel('A').point(lambda v:255 if v>32 else 0).getbbox();cells.append(cell.crop(box))
scale=min(224/max(c.width for c in cells),224/max(c.height for c in cells))
atlas=Image.new('RGBA',(1024,512));frames=[]
for n,cell in enumerate(cells):
 cell=cell.resize((round(cell.width*scale),round(cell.height*scale)),Image.Resampling.LANCZOS)
 x=n%4*256+(256-cell.width)//2;y=n//4*256+240-cell.height
 atlas.alpha_composite(cell,(x,y));frames.append({'x':n%4*256,'y':n//4*256,'w':256,'h':256,'ax':128,'ay':240})
atlas.save(root/'assets/maisie.webp',quality=89,method=6)
meta={'width':1024,'height':512,'frames':frames,'idle':[0,1],'walk':[2,3,4,5,6,7],'standingWidth':1.6,'source':'Original Maisie photographs, generated approved pose sheet; constant scale and foot anchor.'}
(root/'src/maisie-meta.js').write_text('// Generated by tools/prepare-maisie.py.\nexport const MAISIE_META = '+json.dumps(meta,separators=(',',':'))+';\n')
(root/'docs/plans/kitchen-workshop/art/maisie/metadata.json').write_text(json.dumps(meta,indent=2)+'\n')
print((root/'assets/maisie.webp').stat().st_size)
