// Derive collision bodies from the actual home voxel models.
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import * as THREE from "three";
import { HOME_FURNISHINGS } from "../src/content/home-furnishings.js";
import { homeFurnishingProp } from "../src/home-furnishings.js";
const round=n=>Math.round(n*1000)/1000;
const sizes=Object.fromEntries(HOME_FURNISHINGS.map(item=>{
  const box=new THREE.Box3().setFromObject(homeFurnishingProp(item.id));
  return [item.id,{box:[box.min.x,box.max.x,box.min.z,box.max.z,box.max.y].map(round)}];
}));
fs.writeFileSync(fileURLToPath(new URL("../src/content/home-furnishing-sizes.js",import.meta.url)),
  "// Generated by tools/measure-home-furnishings.mjs from the native home models.\nexport const HOME_FURNISHING_SIZES = "+JSON.stringify(sizes,null,2)+";\n");
console.log("Measured "+HOME_FURNISHINGS.length+" home furnishings.");
