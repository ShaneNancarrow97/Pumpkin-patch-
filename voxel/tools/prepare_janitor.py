"""Normalise the approved eight-pose Hettie sheet without changing her painted art."""
from pathlib import Path
import argparse,json
from PIL import Image

p=argparse.ArgumentParser();p.add_argument('source',type=Path);a=p.parse_args()
root=Path(__file__).resolve().parents[1];image=Image.open(a.source).convert('RGBA')
slots=[]
for row in range(2):
 for col in range(4):
  cell=image.crop((col*image.width//4,row*image.height//2,(col+1)*image.width//4,(row+1)*image.height//2))
  bounds=cell.getchannel('A').point(lambda n:255 if n>12 else 0).getbbox()
  assert bounds,'Empty janitor pose'
  slots.append(cell.crop(bounds))
scale=min(172/max(s.width for s in slots),236/max(s.height for s in slots))
sheet=Image.new('RGBA',(768,512));frames=[];height=0
for i,s in enumerate(slots):
 s=s.resize((round(s.width*scale),round(s.height*scale)),Image.Resampling.LANCZOS);height=max(height,s.height)
 sheet.alpha_composite(s,((i%4)*192+(192-s.width)//2,(i//4)*256+244-s.height))
 frames.append({'x':i%4*192,'y':i//4*256,'w':192,'h':256,'ax':96,'ay':244})
sheet.save(root/'assets/hettie-janitor.webp',quality=88,method=6,exact=True)
first=slots[0];size=min(first.width,round(first.height*.43));cx=first.width//2
portrait=first.crop((max(0,cx-size//2),0,min(first.width,cx+size//2),size)).resize((128,128),Image.Resampling.LANCZOS)
portrait.save(root/'assets/hettie-janitor-icon.webp',quality=90,method=6,exact=True)
meta={'w':768,'h':512,'height':height,'walk':frames[:4],'sweep':frames[4:]}
(root/'src/janitor-meta.js').write_text('// Generated by tools/prepare_janitor.py from the approved Hettie poses.\nexport const JANITOR_META='+json.dumps(meta,separators=(',',':'))+';\n')
print('Normalised Hettie:',height,'pixel shared height; runtime bytes:',(root/'assets/hettie-janitor.webp').stat().st_size)
