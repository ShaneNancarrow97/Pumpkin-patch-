#!/usr/bin/env python3
"""Crop and normalise generated reward artwork. This does not draw sprite art."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'assets/level-rewards'
SOURCE = OUTPUT / 'source.png'
IDS = ['rank-seed', 'rank-lantern', 'rank-moon', 'rank-moth', 'rank-manor', 'rank-eclipse',
       'coins', 'upgrade', 'decor', 'costume', 'recipe', 'area']
NUMBER_Y = {'rank-seed': 46, 'rank-lantern': 44, 'rank-moon': 50,
            'rank-moth': 52, 'rank-manor': 59, 'rank-eclipse': 50}
COLUMNS, ROWS, CELL, INSET = 4, 3, 128, 10


def main():
    source = Image.open(SOURCE).convert('RGBA')
    atlas = Image.new('RGBA', (COLUMNS * CELL, ROWS * CELL))
    records = []
    (OUTPUT / 'individual').mkdir(exist_ok=True)
    for index, name in enumerate(IDS):
        column, row = index % COLUMNS, index // COLUMNS
        bounds = (column * source.width // COLUMNS, row * source.height // ROWS,
                  (column + 1) * source.width // COLUMNS, (row + 1) * source.height // ROWS)
        tile = source.crop(bounds)
        # Drop near-transparent background speckle, preserving antialiasing and
        # the original generated painted pixels at all meaningful alpha values.
        tile.putalpha(tile.getchannel('A').point(lambda a: 0 if a < 24 else a))
        content = tile.getbbox()
        if not content:
            raise ValueError('Empty generated icon: ' + name)
        tile = tile.crop(content)
        tile.thumbnail((CELL - INSET * 2, CELL - INSET * 2), Image.Resampling.LANCZOS)
        packed = Image.new('RGBA', (CELL, CELL))
        packed.alpha_composite(tile, ((CELL - tile.width) // 2, (CELL - tile.height) // 2))
        packed.save(OUTPUT / 'individual' / (name + '.png'), optimize=True)
        atlas.alpha_composite(packed, (column * CELL, row * CELL))
        item = {'id': name, 'column': column, 'row': row, 'sourceBounds': list(bounds),
                'contentBounds': list(content), 'renderSize': list(tile.size)}
        if name in NUMBER_Y:
            item['numberY'] = NUMBER_Y[name]
            centre = packed.getpixel((CELL // 2, round(CELL * NUMBER_Y[name] / 100)))
            if centre[3] < 200 or max(centre[:3]) > 125:
                raise ValueError('Number anchor is not on a quiet opaque centre: ' + name)
        records.append(item)
    atlas.save(OUTPUT / 'level-rewards.webp', lossless=True, method=6)
    manifest = {'generatedBy': 'tools/bake-level-reward-icons.py', 'source': 'assets/level-rewards/source.png',
                'sourceSha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(), 'sourceSize': list(source.size),
                'grid': {'columns': COLUMNS, 'rows': ROWS, 'cell': CELL, 'inset': INSET}, 'items': records,
                'runtime': {'file': 'level-rewards.webp', 'bytes': (OUTPUT / 'level-rewards.webp').stat().st_size,
                            'sha256': hashlib.sha256((OUTPUT / 'level-rewards.webp').read_bytes()).hexdigest()}}
    (OUTPUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    meta = '// Generated by tools/bake-level-reward-icons.py; change source art, then rebake.\n'
    meta += 'export const LEVEL_REWARD_GRID = Object.freeze(' + json.dumps(manifest['grid']) + ');\n'
    meta += 'export const LEVEL_REWARD_ICONS = Object.freeze(' + json.dumps({
        item['id']: {key: item[key] for key in ['column', 'row', 'numberY'] if key in item} for item in records
    }, indent=2) + ');\n'
    (ROOT / 'src/content/level-reward-icon-meta.js').write_text(meta)

    # Proof at reward-card, hotbar and compact sizes. Numerals exist only on
    # this technical preview and in DOM markup, never in the runtime atlas.
    preview = Image.new('RGB', (640, 636), '#271e31')
    draw = ImageDraw.Draw(preview)
    font_path = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
    for index, name in enumerate(IDS):
        x, y = index % COLUMNS * 160, index // COLUMNS * 212
        tile = atlas.crop((index % COLUMNS * CELL, index // COLUMNS * CELL,
                           (index % COLUMNS + 1) * CELL, (index // COLUMNS + 1) * CELL))
        preview.paste(tile, (x + 16, y), tile)
        if name in NUMBER_Y:
            level = [1, 5, 9, 13, 17, 20][index]
            font = ImageFont.truetype(font_path, 34)
            draw.text((x + 80, y + CELL * NUMBER_Y[name] / 100), str(level), anchor='mm',
                      fill='#fff1d4', stroke_width=1, stroke_fill='#21132c', font=font)
        for edge, dx in [(44, 35), (28, 97)]:
            tiny = tile.resize((edge, edge), Image.Resampling.LANCZOS)
            preview.paste(tiny, (x + dx, y + 135), tiny)
        draw.text((x + 12, y + 188), name, fill='#e9d9b9')
    preview.save(OUTPUT / 'contact-preview.jpg', quality=94, subsampling=0)
    print('Packed', len(IDS), 'painted level/reward icons:', manifest['runtime']['bytes'], 'bytes')


if __name__ == '__main__':
    main()
