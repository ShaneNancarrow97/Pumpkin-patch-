"""Normalise generated whole-sheet home poses without changing their artwork."""
from pathlib import Path
from PIL import Image
from scipy import ndimage
import numpy as np,json
root=Path(__file__).resolve().parents[1]
source=Image.open(root/'docs/plans/life-play/art/owner-home-poses.png').convert('RGBA')
slot=(256,320);out=Image.new('RGBA',(slot[0]*3,slot[1]*2));meta={}
for row,who in enumerate(['shane','natalie']):
 frames=[]
 for col in range(3):
  f=source.crop((col*source.width//3,row*source.height//2,(col+1)*source.width//3,(row+1)*source.height//2));mask=np.asarray(f.getchannel('A'))>=96;labels,n=ndimage.label(mask);areas=np.bincount(labels.ravel());areas[0]=0;main=labels==int(areas.argmax());ys,xs=np.where(main);near=np.zeros_like(main);near[max(0,ys.min()-5):ys.max()+6,max(0,xs.min()-5):xs.max()+6]=True
  for i in range(1,n+1):
   if areas[i]>8 and np.any((labels==i)&near):main|=labels==i
  f.putalpha(Image.fromarray((main*255).astype('uint8')));f=f.crop(f.getchannel('A').getbbox());frames.append(f)
 scale=min(300/max(f.height for f in frames),244/max(f.width for f in frames))
 rects=[]
 for col,f in enumerate(frames):
  f=f.resize((round(f.width*scale),round(f.height*scale)),Image.Resampling.LANCZOS);x=col*slot[0]+(slot[0]-f.width)//2;y=row*slot[1]+310-f.height;out.alpha_composite(f,(x,y));rects.append(dict(x=col*slot[0],y=row*slot[1],w=slot[0],h=slot[1],ax=slot[0]/2,ay=310))
 meta[who]={kind:rects[i] for i,kind in enumerate(['sit','read','pet'])}
(root/'assets/owner-home-poses.webp').parent.mkdir(exist_ok=True)
out.save(root/'assets/owner-home-poses.webp','WEBP',quality=90,method=6,exact=True)
(root/'src/owner-home-pose-meta.js').write_text('// Generated by tools/bake_home_poses.py.\nexport const HOME_POSE_META = '+json.dumps(dict(w=out.width,h=out.height,rows=400,owners=meta),separators=(',',':'))+';\n')
print('home poses',out.size,(root/'assets/owner-home-poses.webp').stat().st_size)
