#!/usr/bin/env python3
"""Normalise generated owner turnarounds with shared scale and foot anchors.

Source images are whole-sheet edits of the shipped owner/costume artwork.
This only crops, aligns and compresses; it does not synthesize character art.
"""
from pathlib import Path
from PIL import Image
import numpy as np
from scipy import ndimage
import json

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'docs/plans/home-play/art'
SLOT = (280, 340)
meta = {}


def crop(source, row, col, bounds, flip=False):
    y0, y1 = bounds[row]
    w = source.width / 4
    frame = source.crop((round(col*w), y0, round((col+1)*w), y1))
    # Imagegen alpha can leave almost invisible background colour. Only alpha
    # determines the silhouette; RGB is never used as a chroma key.
    mask = np.array(frame.getchannel('A')) >= 96
    # Generators occasionally let a neighbour's boot cross a nominal grid line.
    # Keep the figure's connected silhouette, never an adjacent cell's fragment.
    labels, count = ndimage.label(mask)
    areas = np.bincount(labels.ravel()); areas[0] = 0
    body = int(areas.argmax())
    main = labels == body
    ys, xs = np.where(main)
    if not len(xs):
        raise ValueError(f'Empty silhouette row {row} column {col}')
    near = np.zeros_like(main)
    near[max(0,ys.min()-4):ys.max()+5,max(0,xs.min()-4):xs.max()+5] = True
    for component in range(1,count+1):
        if component != body and areas[component] >= 4 and np.any((labels==component)&near):
            main |= labels==component
    alpha = Image.fromarray((main*255).astype('uint8'))
    frame.putalpha(alpha)
    box = alpha.getbbox()
    if box is None:
        raise ValueError(f'Empty frame row {row} column {col}')
    frame = frame.crop(box)
    return frame.transpose(Image.Transpose.FLIP_LEFT_RIGHT) if flip else frame


def bake(name, filename, ids, bounds, base=False):
    source = Image.open(ART / filename).convert('RGBA')
    output = Image.new('RGBA', (SLOT[0]*4, SLOT[1]*len(bounds)))
    rows = []
    for row in range(len(bounds)):
        frames = [crop(source,row,col,bounds,flip=name=='shane-a' and col==0) for col in range(4)]
        # The relaxed pose sets action-row scale so crouching remains crouching.
        scale = 320 / (frames[3].height if base and row in [2,5] else max(f.height for f in frames))
        # Extremely wide crouches/capes must keep a little gutter.
        scale = min(scale, (SLOT[0]-12)/max(f.width for f in frames))
        rects = []
        for col, frame in enumerate(frames):
            frame = frame.resize((round(frame.width*scale),round(frame.height*scale)),Image.Resampling.LANCZOS)
            x, y = col*SLOT[0] + (SLOT[0]-frame.width)//2, row*SLOT[1]+330-frame.height
            output.alpha_composite(frame,(x,y))
            rects.append({'x':col*SLOT[0],'y':row*SLOT[1],'w':SLOT[0],'h':SLOT[1],'ax':SLOT[0]/2,'ay':330})
        rows.append(rects)
    path = ROOT / f'assets/player-directions-{name}.webp'
    output.save(path,'WEBP',quality=88,method=6,exact=True)
    if base:
        for who,offset in [('shane',0),('natalie',3)]:
            meta[who+'-base']={'sheet':name,'w':output.width,'h':output.height,'rows':320,'side':rows[offset],'back':rows[offset+1],'plant':[rows[offset+2][0]],'water':[rows[offset+2][1]],'harvest':[rows[offset+2][2]]}
    else:
        for row,id in enumerate(ids):
            meta[id]={'sheet':name,'w':output.width,'h':output.height,'rows':320,'side':rows[row][:2],'back':rows[row][2:]}
    print(path.name,path.stat().st_size)


bake('base','player-base-actions.png',[],[(0,258),(258,519),(505,758),(758,1004),(1004,1253),(1236,1448)],base=True)
bake('shane-a','shane-costumes-a.png',['shane-vampire','shane-skeleton','shane-scarecrow','shane-frankenstein'],[(0,368),(368,736),(736,1112),(1112,1536)])
bake('shane-b','shane-costumes-b.png',['shane-mummy','shane-slasher','shane-chucky','shane-jason'],[(0,374),(374,746),(746,1109),(1109,1536)])
bake('natalie-a','natalie-costumes-a.png',['natalie-witch','natalie-ghostbride','natalie-batqueen','natalie-vampire','natalie-frankenstein'],[(0,349),(349,684),(684,1014),(1014,1355),(1355,1774)])
bake('natalie-b','natalie-costumes-b.png',['natalie-mummy','natalie-slasher','natalie-tiffany','natalie-freddy','natalie-wheelchair'],[(0,368),(368,710),(710,1064),(1064,1436),(1436,1774)])
(ROOT/'src/player-direction-meta.js').write_text('// Generated by tools/bake_player_directions.py.\nexport const PLAYER_DIRECTION_META = '+json.dumps(meta,separators=(',',':'))+';\n')
