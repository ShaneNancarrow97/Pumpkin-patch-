#!/usr/bin/env python3
"""Index reviewed painted pages; never synthesize an angle or a walk phase."""
from pathlib import Path
from PIL import Image
import argparse, hashlib, json

ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser()
parser.add_argument('--reviewed',action='store_true',help='Operator has inspected every included strip and angle')
args=parser.parse_args()
if not args.reviewed: parser.error('Inspect the previews first, then use --reviewed; this is not automatic art approval.')
phases=['contact-left','down-left','passing-left','up-left','contact-right','down-right','passing-right','up-right']
bank={'version':1,'angleConvention':'0 front, 90 screen-right, 180 back, 270 screen-left; nominal painted bearings','looks':{}}
imports=[];urls={};total=0
for owner in ['shane','natalie']:
    path=ROOT/f'assets/directional/{owner}/base.json'
    if not path.exists(): continue
    raw=json.loads(path.read_text());look=raw['look'];density=raw['rows']/raw.get('worldHeight',2.3)
    # Optional working gestures are authored separately, with the same body scale.
    actions_path=ROOT/f'assets/directional/actions/{owner}.json'
    if actions_path.exists():
        extra=json.loads(actions_path.read_text())
        if extra['rows']/extra.get('worldHeight',2.3)!=density: raise ValueError(f'{owner}: gesture density differs from standing body')
        for key,p in extra['pages'].items():
            if key in raw['pages']:raise ValueError(f'{owner}: duplicate page {key}')
            raw['pages'][key]={**p,'file':str((actions_path.parent/p['file']).relative_to(path.parent,walk_up=True))}
        for action,directions in extra['actions'].items():
            into=raw['actions'].setdefault(action,{})
            if set(into)&set(directions):raise ValueError(f'{owner}: duplicate action bearings {action}')
            into.update({degree:{**clip,'preview':'docs/plans/directional-cast/actions/README.md'} for degree,clip in directions.items()})
    seed=ROOT/f'docs/plans/directional-cast/{owner}/approved-front-seed.png'
    if not seed.exists():seed=ROOT/f'docs/plans/directional-cast/{owner}/approved-front.png'
    if not seed.exists():raise ValueError(f'{owner}: source seed missing')
    m={'version':1,'owner':owner,'look':look,'mobility':'walking','sourceSeed':seed.relative_to(ROOT).as_posix(),'pixelsPerUnit':density,'pages':[],'clips':[]}
    images={}
    for key,p in raw['pages'].items():
        file=(path.parent/p['file']).resolve();url=file.relative_to(ROOT).as_posix();image=Image.open(file).convert('RGBA');images[key]=image
        m['pages'].append({'id':key,'url':url,'width':image.width,'height':image.height,'encodedBytes':file.stat().st_size,'encodedSHA256':hashlib.sha256(file.read_bytes()).hexdigest()})
        if url not in urls:
            var='page'+str(len(imports));imports.append(f'import {var} from {json.dumps("../"+url)};');urls[url]=var;total+=file.stat().st_size
    for action,directions in raw['actions'].items():
        for degree,c in directions.items():
            frames=[]
            reduced=c.get('mode')=='reduced'
            expected=4 if reduced and action in ['walk','jog'] else {'idle':1,'walk':8,'jog':8,'plant':6,'water':6,'harvest':6,'clean':6,'interact':6,'sit':4,'read':4,'pet':6,'cook':8,'carve':8}[action]
            if len(c['frames'])!=expected: raise ValueError(f'{look}/{action}/{degree}: wrong frame count')
            for i,f in enumerate(c['frames']):
                r={key:f[key] for key in ['x','y','w','h']};pixels=images[c['page']].crop((r['x'],r['y'],r['x']+r['w'],r['y']+r['h']))
                frame={'page':c['page'],'rect':r,'anchor':{'x':f['ax'],'y':f['ay']},'pixelsPerUnit':density,'fingerprint':hashlib.sha256(pixels.tobytes()).hexdigest()}
                if 'sockets' in f: frame['sockets']=f['sockets']
                if action in ['walk','jog']:frame['phase']=phases[[0,2,4,6][i] if reduced else i]
                frames.append(frame)
            clip={'action':action,'degree':int(degree),'authoring':'drawn','review':{'approved':True,'preview':c.get('preview',f'docs/plans/directional-cast/{owner}/README.md')},'frames':frames}
            if action=='idle':clip['mode']='pose'
            elif reduced:clip['mode']='reduced'
            m['clips'].append(clip)
    bank['looks'][look]=m
out=ROOT/'assets/directional/manifest.json';out.write_text(json.dumps(bank,indent=2)+'\n')
(ROOT/'src/directional-pages.js').write_text('// Generated by tools/index_directional_assets.py.\n'+'\n'.join(imports)+'\nexport const directionalPageURLs={'+','.join(json.dumps(k)+':'+v for k,v in urls.items())+'};\n')
print(json.dumps({'looks':list(bank['looks']),'pages':len(urls),'encodedBytes':total,'clips':sum(len(m['clips']) for m in bank['looks'].values())}))
