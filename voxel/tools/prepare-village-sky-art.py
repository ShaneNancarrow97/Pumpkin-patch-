#!/usr/bin/env python3
"""Prepare the unchanged original sky painting as a bounded dome texture."""
from pathlib import Path
from PIL import Image
import hashlib, json

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'assets/village-fidelity-concepts/dusk-sky-source.png'
target = ROOT / 'assets/village-fidelity/dusk-sky.webp'
original = Image.open(source).convert('RGB')
assert original.width == original.height * 2, 'Preserve the original panorama aspect'
original.resize((1024, 512), Image.Resampling.LANCZOS).save(target, 'WEBP', quality=90, method=6)
w, h, mip_bytes = 1024, 512, 0
while True:
    mip_bytes += w * h * 4
    if w == h == 1: break
    w, h = max(1, w // 2), max(1, h // 2)
meta = {'width': 1024, 'height': 512, 'encodedBytes': target.stat().st_size,
        'baseRgbaBytes': 1024 * 512 * 4, 'estimatedMipRgbaBytes': mip_bytes,
        'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest(),
        'sha256': hashlib.sha256(target.read_bytes()).hexdigest(),
        'processing': 'Aspect-preserving Lanczos resize and WebP encoding. Original painting retained; no repainting.'}
(target.parent / 'dusk-sky-receipt.json').write_text(json.dumps(meta, indent=2) + '\n')
(ROOT / 'src/content/village-sky-art-meta.js').write_text('// Generated by tools/prepare-village-sky-art.py.\nexport const VILLAGE_SKY_ART_META = Object.freeze(' + json.dumps({k: meta[k] for k in ['width', 'height', 'encodedBytes', 'baseRgbaBytes', 'estimatedMipRgbaBytes', 'sha256']}, separators=(',', ':')) + ');\n')
print(json.dumps(meta, indent=2))
