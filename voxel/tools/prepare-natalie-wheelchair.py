from PIL import Image
from pathlib import Path
import json
r=Path(__file__).resolve().parents[1];im=Image.open(r/'docs/plans/kitchen-workshop/art/natalie-wheelchair/source.png').convert('RGBA');parts=[]
for i in range(8):
 c=im.crop((i%4*im.width//4,i//4*im.height//2,(i%4+1)*im.width//4,(i//4+1)*im.height//2))
 b=c.getchannel('A').point(lambda a:255 if a>40 else 0).getbbox();parts.append(c.crop(b))
scale=min(288/max(c.width for c in parts),296/max(c.height for c in parts));out=Image.new('RGBA',(1280,640));frames=[]
for i,c in enumerate(parts):
 c=c.resize((round(c.width*scale),round(c.height*scale)),Image.Resampling.LANCZOS)
 out.alpha_composite(c,(i%4*320+(320-c.width)//2,i//4*320+310-c.height));frames.append({'x':i%4*320,'y':i//4*320,'w':320,'h':320,'ax':160,'ay':310})
out.save(r/'assets/natalie-wheelchair.webp',quality=91,method=6)
meta={'w':1280,'h':640,'rows':340,'idle':frames[:2],'walk':frames[2:]}
(r/'src/natalie-wheelchair-meta.js').write_text('// Generated by tools/prepare-natalie-wheelchair.py.\nexport const WHEELCHAIR_META = '+json.dumps({'natalie-wheelchair':meta},separators=(',',':'))+';\n')
(r/'docs/plans/kitchen-workshop/art/natalie-wheelchair/metadata.json').write_text(json.dumps(meta,indent=2)+'\n')
print((r/'assets/natalie-wheelchair.webp').stat().st_size)
