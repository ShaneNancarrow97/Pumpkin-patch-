"""Prepare Sandy's lean redraw with a shared scale and stable paw anchors.

Only alpha cleaning, cropping and packing happen here. The art is generated as
whole sheets; Skyla and Maisie's approved pixels are retained exactly.
"""
from pathlib import Path
import json, hashlib
from PIL import Image
import numpy as np
from scipy import ndimage

ROOT=Path(__file__).resolve().parents[1]
ART=ROOT/'docs/plans/directional-cast/sandy'
source=Image.open(ART/'lean-states-source.png').convert('RGBA')
walk_source=Image.open(ART/'lean-walk-source.png').convert('RGBA')

def figure(slot):
    a=np.asarray(slot.getchannel('A'))
    labels,n=ndimage.label(a>=72)
    counts=np.bincount(labels.ravel());counts[0]=0
    body=labels==counts.argmax()
    # Keep fine whiskers at the main silhouette, but no nearly invisible haze.
    mask=ndimage.binary_dilation(body,iterations=3)
    out=slot.copy();alpha=np.where(mask&(a>=32),a,0).astype('uint8')
    out.putalpha(Image.fromarray(alpha))
    bounds=out.getchannel('A').point(lambda p:255 if p>=96 else 0).getbbox()
    if bounds is None:raise ValueError('Empty Sandy pose')
    return out.crop(bounds)

bounds=[0,372,670,1024]
poses=[figure(source.crop((i%4*384,bounds[i//4],(i%4+1)*384,bounds[i//4+1])))for i in range(11)]
walk=[figure(walk_source.crop((round(i*walk_source.width/4),0,round((i+1)*walk_source.width/4),walk_source.height)))for i in range(4)]
# A single scale across home poses, including lying/stretching: never expand a
# sleeping dog back to standing height. The walking sheet gets one shared scale.
scale=min(236/max(p.width for p in poses),172/max(p.height for p in poses))
walk_scale=poses[0].width*scale / (sum(p.width for p in walk)/len(walk))

def pack(p,size,anchor,factor):
    p=p.resize((round(p.width*factor),round(p.height*factor)),Image.Resampling.LANCZOS)
    result=Image.new('RGBA',size);result.alpha_composite(p,(round(anchor[0]-p.width/2),round(anchor[1]-p.height)))
    return result

approved=Image.open(ART/'home-pets-approved.png').convert('RGBA')
current=Image.open(ROOT/'assets/home-pets.webp').convert('RGBA')
if not np.array_equal(np.array(current.crop((0,0,1024,768))),np.array(approved.crop((0,0,1024,768)))):
    raise ValueError('Other pet art changed: review and update the approved base before rebaking Sandy')
atlas=Image.new('RGBA',(1024,1152));atlas.paste(approved.crop((0,0,1024,768)),(0,0))
# Preserve the existing two-pose walk contract. The generated opposite contacts
# repeat the same leading leg, so they are not sold as a complete four-phase gait.
sandy=[poses[0],walk[0],walk[1],poses[3],poses[4],poses[5],poses[6],poses[7]]
frames=[];metrics=[]
for n,p in enumerate(sandy):
    factor=walk_scale if n in [1,2] else scale
    cell=pack(p,(256,192),(128,184),factor)
    x=n%4*256;y=768+n//4*192;atlas.paste(cell,(x,y))
    frames.append(dict(x=x,y=y,w=256,h=192,ax=128,ay=184))
    b=cell.getchannel('A').point(lambda p:255 if p>=96 else 0).getbbox()
    metrics.append({'frame':n,'bounds':b,'hash':hashlib.sha256(cell.tobytes()).hexdigest()})
# Lossless WebP keeps every approved cat/terrier alpha and colour value identical.
atlas.save(ROOT/'assets/home-pets.webp','WEBP',lossless=True,method=6,exact=True)
meta=json.loads((ART/'home-pets-approved-meta.json').read_text())
meta['pets']['sandy']={'frames':frames,'width':1.45}
(ROOT/'src/home-pets-meta.js').write_text('// Generated by tools/bake_sandy_lean.py; original cat/terrier retained.\nexport const HOME_PETS_META = '+json.dumps(meta,separators=(',',':'))+';\n')

cashier_scale=scale*2*1.45/1.8
for n,name in enumerate(['idle','blink','serve']):
    cell=pack(poses[8+n],(512,320),(256,312),cashier_scale)
    cell.save(ROOT/f'assets/sandy/lean-{name}.webp','WEBP',quality=92,method=6,exact=True)
# The approved service bell remains a separate immutable item, not part of her body.
bell=Image.open(ROOT/'assets/sandy/sandy-serve.png').convert('RGBA').crop((135,810,325,943))
bell.save(ROOT/'assets/sandy/service-bell.webp','WEBP',lossless=True,method=6,exact=True)
head=figure(source.crop((235,100,380,268)));head.thumbnail((104,104),Image.Resampling.LANCZOS)
portrait=Image.new('RGBA',(112,112));portrait.alpha_composite(head,((112-head.width)//2,(112-head.height)//2))
portrait.save(ROOT/'assets/sandy/lean-portrait.webp','WEBP',quality=94,method=6,exact=True)

preview=Image.new('RGBA',atlas.size,(38,32,46));preview.alpha_composite(atlas)
preview.convert('RGB').save(ART/'lean-pet-preview.jpg',quality=92)
loop=[]
for n in [1,2]:
    f=frames[n];im=Image.new('RGBA',(256,192),(38,32,46));im.alpha_composite(atlas.crop((f['x'],f['y'],f['x']+256,f['y']+192)));loop.append(im.convert('RGB'))
loop[0].save(ART/'sandy-walk.gif',save_all=True,append_images=loop[1:],duration=160,loop=0)
metrics={'homeWidth':1.45,'cashierWidth':1.8,'homeSourceScale':scale,'walkSourceScale':walk_scale,'frames':metrics,'runtimeBytes':{p.name:p.stat().st_size for p in [ROOT/'assets/home-pets.webp',*[ROOT/f'assets/sandy/lean-{name}.webp'for name in ['idle','blink','serve','portrait']],ROOT/'assets/sandy/service-bell.webp']}}
decoded=Image.open(ROOT/'assets/home-pets.webp').convert('RGBA')
assert np.array_equal(np.array(decoded.crop((0,0,1024,768))),np.array(approved.crop((0,0,1024,768))))
metrics['approvedTopPixelHash']=hashlib.sha256(approved.crop((0,0,1024,768)).tobytes()).hexdigest()
metrics['runtimeHashes']={p:hashlib.sha256((ROOT/'assets'/('home-pets.webp' if p=='home-pets.webp' else 'sandy/'+p)).read_bytes()).hexdigest()for p in metrics['runtimeBytes']}
(ART/'measurements.json').write_text(json.dumps(metrics,indent=2)+'\n')
print(json.dumps(metrics,indent=2))
